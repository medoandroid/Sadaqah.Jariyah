// Fallback & default reciters alias
export const RECITERS: Reciter[] = EXPANDED_RECITERS;

export const getSurahAudioUrl = (reciter: Reciter, surahNumber: number): string => {
  const padded = String(surahNumber).padStart(3, '0');
  const cleanServer = reciter.serverUrl.replace(/\/+$/, '');
  return `${cleanServer}/${padded}.mp3`;
};

export const getSurahFallbackAudioUrl = (surahNumber: number): string => {
  const padded = String(surahNumber).padStart(3, '0');
  return `https://server8.mp3quran.net/afs/${padded}.mp3`;
};
