/**
 * Returns a deterministic daily Tadabbur based on day of year,
 * ensuring consistency throughout the day.
 */
export function getDailyTadabbur(date: Date = new Date()): TadabburItem {
  const startOfYear = new Date(date.getFullYear(), 0, 1);
  const dayIndex = Math.floor((date.getTime() - startOfYear.getTime()) / (1000 * 60 * 60 * 24));
  const itemIndex = Math.abs(dayIndex) % TADABBUR_ITEMS.length;
  return TADABBUR_ITEMS[itemIndex];
}

/**
 * Returns a truly random Tadabbur item different from the current one.
 */
export function getRandomTadabbur(excludeId?: number): TadabburItem {
  const available = excludeId ? TADABBUR_ITEMS.filter((i) => i.id !== excludeId) : TADABBUR_ITEMS;
  const randomIndex = Math.floor(Math.random() * available.length);
  return available[randomIndex];
}
